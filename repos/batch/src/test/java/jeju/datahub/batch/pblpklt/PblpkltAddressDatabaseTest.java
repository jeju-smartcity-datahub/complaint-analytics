import jeju.datahub.batch.pblpklt.api.DhubPblpkltItemReader;

/** 명시적으로 지정한 별도 임시 PostgreSQL DB 에서만 실제 SQL 과 FK 보존을 검증한다. */
@EnabledIfEnvironmentVariable(named = "PBLPKLT_TEST_DB_URL", matches = ".+")
class PblpkltAddressDatabaseTest {
    private JdbcTemplate jdbc;
    private DriverManagerDataSource dataSource;
    private PblpkltItemWriter writer;

    @BeforeEach
    void setUp() throws Exception {
        dataSource = new DriverManagerDataSource(System.getenv("PBLPKLT_TEST_DB_URL"),
                System.getenv("PBLPKLT_TEST_DB_USER"), System.getenv("PBLPKLT_TEST_DB_PASSWORD"));
        jdbc = new JdbcTemplate(dataSource);
        assertThat(jdbc.queryForObject("SELECT current_database()", String.class))
                .startsWith("jeju_pblpklt_test_");
        jdbc.execute("DROP SCHEMA IF EXISTS parking CASCADE; DROP SCHEMA IF EXISTS batch CASCADE;"
                + " CREATE SCHEMA parking; CREATE SCHEMA batch;"
                + " CREATE TABLE parking.tb_admdst (emd_cd varchar(8) PRIMARY KEY);"
                + " INSERT INTO parking.tb_admdst VALUES ('50110250');");
        String base = Files.readString(Path.of("../../database/migrations/sql/02-TB_PBLPKLT.sql"))
                .replaceFirst("pklt_id\\s+VARCHAR\\(20\\) NOT NULL",
                        "pklt_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL");
        jdbc.execute(base);
        jdbc.execute("ALTER TABLE parking.tb_pblpklt ADD COLUMN origin_pk varchar(40) UNIQUE,"
                + " ADD COLUMN pklt_addr varchar(200), ADD COLUMN extsh_dt timestamp;"
                + " ALTER TABLE parking.tb_pblpklt RENAME CONSTRAINT tb_pblpklt_origin_pk_key TO uq_tb_pblpklt_origin_pk;"
                + " CREATE TABLE parking.test_history (pklt_id bigint REFERENCES parking.tb_pblpklt(pklt_id));");
        jdbc.execute(Files.readString(Path.of("../../database/migrations/sql/63-PBLPKLT-SOURCE-EXTENSION.sql")));
        jdbc.execute(Files.readString(Path.of("../../database/migrations/sql/33-TB_PBLPKLT_ADDR_ANOMALY.sql")));
        jdbc.execute(Files.readString(Path.of("../../database/migrations/sql/35-TB_PBLPKLT_ADDR_ANOMALY-UNIQUE.sql")));
        // 곁가지 표의 현재 표준 이름과 타입(마이그레이션 50·70).
        jdbc.execute("ALTER TABLE batch.tb_pblpklt_addr_anomaly ALTER COLUMN pklt_id TYPE varchar(40);"
                + " ALTER TABLE batch.tb_pblpklt_addr_anomaly RENAME COLUMN raw_address TO orgnl_addr;"
                + " ALTER TABLE batch.tb_pblpklt_addr_anomaly RENAME COLUMN detected_at TO detected_dt;");
        writer = new PblpkltItemWriter(dataSource);
    }

    private void migrate() throws Exception {
        jdbc.execute(Files.readString(Path.of("../../database/migrations/sql/112-PBLPKLT-ADDRESS-MATCH.sql")));
    }

    private long existing(String origin, String address) {
        return jdbc.queryForObject("""
                INSERT INTO parking.tb_pblpklt
                  (origin_pk, pklt_addr, pklt_nm, emd_cd, lat, lot, pklt_cpcty)
                VALUES (?, ?, '이전 이름', '50110250', 33.4, 126.5, 1) RETURNING pklt_id
                """, Long.class, origin, address);
    }

    @Test
    void changedOriginIdUpdatesEveryMatchingAddressAndKeepsIdsAndForeignKeys() throws Exception {
        long first = existing("old-1", "같은 주소");
        long second = existing("old-2", "같은 주소");
        long other = existing("new-origin", "다른 주소");
        jdbc.update("INSERT INTO parking.test_history VALUES (?), (?)", first, second);
        jdbc.update("UPDATE parking.tb_pblpklt SET extsh_dt=now() WHERE pklt_id=?", first);
        migrate();
        writer.write(new Chunk<>(List.of(row("new-origin", "같은 주소", 80))));
        assertThat(jdbc.queryForObject("SELECT count(*) FROM parking.tb_pblpklt", Integer.class)).isEqualTo(3);
        assertThat(jdbc.queryForList("SELECT pklt_id FROM parking.tb_pblpklt WHERE pklt_cpcty=80 ORDER BY pklt_id", Long.class))
                .containsExactly(first, second);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM parking.tb_pblpklt WHERE origin_pk='new-origin'", Integer.class)).isEqualTo(3);
        assertThat(jdbc.queryForObject("SELECT pklt_cpcty FROM parking.tb_pblpklt WHERE pklt_id=?", Integer.class, other)).isEqualTo(1);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM parking.test_history", Integer.class)).isEqualTo(2);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM parking.tb_pblpklt WHERE extsh_dt IS NOT NULL", Integer.class)).isZero();
        assertThat(jdbc.queryForObject("SELECT pkltar FROM parking.tb_pblpklt WHERE pklt_id=?", BigDecimal.class, first))
                .isEqualByComparingTo("1234.567890123");
        assertThat(jdbc.queryForObject("SELECT expnd_amt FROM parking.tb_pblpklt WHERE pklt_id=?", BigDecimal.class, first)).isNull();
        migrate(); // 재적용해도 PK/FK 와 데이터를 보존한다.
        assertThat(jdbc.queryForObject("SELECT count(*) FROM parking.test_history", Integer.class)).isEqualTo(2);
    }

    @Test
    void repeatedAddressInOneChunkAndLaterRunsOnlyCreatesOneRow() throws Exception {
        migrate();
        writer.write(new Chunk<>(List.of(row("1", "새 주소", 10), row("2", "새 주소", 20))));
        long id = jdbc.queryForObject("SELECT pklt_id FROM parking.tb_pblpklt", Long.class);
        writer.write(new Chunk<>(List.of(row("3", "새 주소", 30))));
        assertThat(jdbc.queryForObject("SELECT count(*) FROM parking.tb_pblpklt", Integer.class)).isEqualTo(1);
        assertThat(jdbc.queryForObject("SELECT pklt_id FROM parking.tb_pblpklt", Long.class)).isEqualTo(id);
        assertThat(jdbc.queryForObject("SELECT pklt_cpcty FROM parking.tb_pblpklt", Integer.class)).isEqualTo(30);
        // 주소가 달라지면 같은 원천 ID 여도 별도 주차장이다.
        writer.write(new Chunk<>(List.of(row("3", "또 다른 주소", 40))));
        assertThat(jdbc.queryForObject("SELECT count(*) FROM parking.tb_pblpklt", Integer.class)).isEqualTo(2);
    }

    @Test
    void softDeletionUsesAddressesEvenWhenOriginIdsChangeOrRepeat() throws Exception {
        long first = existing("old-1", "유지 주소");
        long second = existing("old-2", "유지 주소");
        long missing = existing("old-3", "소멸 주소");
        long manual = existing(null, "수동 등록 주소");
        migrate();
        mark(Set.of("유지 주소"));
        assertThat(jdbc.queryForList("SELECT pklt_id FROM parking.tb_pblpklt WHERE extsh_dt IS NULL ORDER BY pklt_id", Long.class))
                .containsExactly(first, second, manual);
        assertThat(jdbc.queryForObject("SELECT extsh_dt IS NOT NULL FROM parking.tb_pblpklt WHERE pklt_id=?", Boolean.class, missing)).isTrue();
    }

    @Test
    void aFailedChunkRollsBackAddressUpdates() throws Exception {
        long id = existing("old", "기존 주소");
        migrate();
        TransactionTemplate tx = new TransactionTemplate(new DataSourceTransactionManager(dataSource));
        assertThatThrownBy(() -> tx.executeWithoutResult(status -> {
            writer.write(new Chunk<>(List.of(row("new", "기존 주소", 100))));
            throw new IllegalStateException("fixture failure");
        })).isInstanceOf(IllegalStateException.class);
        assertThat(jdbc.queryForObject("SELECT pklt_cpcty FROM parking.tb_pblpklt WHERE pklt_id=?", Integer.class, id)).isEqualTo(1);
        assertThat(jdbc.queryForObject("SELECT origin_pk FROM parking.tb_pblpklt WHERE pklt_id=?", String.class, id)).isEqualTo("old");
    }

    private void mark(Set<String> addresses) {
        DhubPblpkltItemReader reader = mock(DhubPblpkltItemReader.class);
        when(reader.getSeenAddresses()).thenReturn(addresses);
        var job = MetaDataInstanceFactory.createJobExecution();
        job.createStepExecution("pblpkltFetchStep").setStatus(BatchStatus.COMPLETED);
        var step = job.createStepExecution("pblpkltSoftDeleteStep");
        new PblpkltSoftDeleteMarkingTasklet(dataSource, reader).execute(
                new StepContribution(step), new ChunkContext(new StepContext(step)));
    }

    private static PblpkltRecord row(String origin, String address, int capacity) {
        return new PblpkltRecord(origin, "최신 이름", "50110250", new BigDecimal("33.4"),
                new BigDecimal("126.5"), capacity, "OFSTR", address, List.of(),
                null, null, "테스트동", "노외공영", new BigDecimal("1234.567890123"), "Y", null,
                null, null, null, new BigDecimal("1.25"), null, new BigDecimal("2000"), null,
                null, null, null, null, null, null, null, null, null, null, "검증");
    }
}
