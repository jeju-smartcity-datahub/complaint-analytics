package jeju.datahub.parking.service;

import java.math.BigDecimal;

import io.swagger.v3.oas.annotations.media.Schema;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.ToString;

/**
 * 공영주차장 목록 1건. ({@code GET /api/parking-lots} 응답)
 *
 * <p>단순 마커 표시용. 좌표는 배치에서 VWorld 지오코딩 완료되어 있어
 * 추가 enrich 단계 불필요.
 *
 * <p>🔁 2026-09-21 (Step): 마커 팝업용 4필드(주소·행정동명·주차면수·주차요금여부) 추가.
 *
 * <p>🔁 2026-09-30: 주차장 유형 2필드({@code pkltTypeCd}·{@code pkltTypeNm})를 포함한다.
 * 유형명은 원천 원문이 아니라 공통코드 {@code PKLT_TYPE_CD} 의 {@code cd_nm} 이다.
 *
 * * 컬럼(스네이크) → 필드(카멜) 매핑은 mybatis.configuration.map-underscore-to-camel-case=true 로 자동 처리.
 * * 매퍼는 {@code SELECT p.pklt_id, p.pklt_nm, p.lat, p.lot, p.pklt_addr, p.emd_nm, p.pklt_cpcty, p.prk_crg_yn, p.pklt_type_cd, cd.cd_nm FROM parking.tb_pblpklt p LEFT JOIN parking.tb_com_cd cd ON cd.group_cd = 'PKLT_TYPE_CD' AND cd.cd_vl = p.pklt_type_cd WHERE p.lat IS NOT NULL AND p.lot IS NOT NULL AND p.extsh_dt IS NULL} 이다(공통코드 LEFT JOIN 1건).
 *   좌표 NULL 행은 지도에 못 놓으므로 응답에서 제외한다(가독성보다 데이터 정합성 우선).
 */
@Schema(description = "공영주차장 1건 (지도 마커용)")
@Getter
@Setter
@ToString
@NoArgsConstructor
public class ParkingLotVO {

    /**
     * 주차장 ID (TB_PBLPKLT.pklt_id).
     *
     * <p>🔁 2026-09-18 (C′): String → Long. 마이그레이션 70 이
     * {@code pklt_id} 를 {@code character varying(20)} 에서 {@code BIGINT GENERATED BY
     * DEFAULT AS IDENTITY} 로 바꿨다 — 배치의 인메모리 순번 카운터를 없애기 위해
     * <b>채번 주체를 DB 로 옮긴 것</b>이고, 값은 DB 가 매긴 일련번호라 업무적 의미가 없다.
     *
     * <p>이로써 <b>2026-09-04 의 "long → String 정정" 사유가 소멸</b>했다. 그때는 시드의
     * {@code 구좌-0001} 같은 비숫자 자체 배정값이 파싱에 실패해 {@code /api/parking-lots}
     * 가 500 으로 떨어졌었다. 그 형식 자체가 폐지돼(원천 식별자는 {@code origin_pk} 가
     * 진다) 비숫자 값이 들어올 경로가 없다. 프론트 {@code ParkingLotItem.pkltId} 는
     * 이미 {@code number} 였으므로 오히려 계약이 맞춰진 것이다.
     */
    @Schema(description = "주차장 ID (DB 채번 일련번호)", example = "1")
    private Long pkltId;

    /** 주차장명 (TB_PBLPKLT.pklt_nm) */
    @Schema(description = "주차장명", example = "제주시청 제1공영주차장")
    private String pkltNm;

    /** 위도 (TB_PBLPKLT.lat) */
    @Schema(description = "위도", example = "33.4996")
    private BigDecimal lat;

    /** 경도 (TB_PBLPKLT.lot) */
    @Schema(description = "경도", example = "126.5312")
    private BigDecimal lot;

    /** 주차장주소 (TB_PBLPKLT.pklt_addr) */
    @Schema(description = "주차장 주소", example = "노형동 947")
    private String pkltAddr;

    /** 행정동명 (TB_PBLPKLT.emd_nm) */
    @Schema(description = "행정동명", example = "노형동")
    private String emdNm;

    /** 주차면수 (TB_PBLPKLT.pklt_cpcty). 원천 결측이면 null */
    @Schema(description = "주차 면수 (원천 결측이면 null)", example = "42", nullable = true)
    private Integer pkltCpcty;

    /**
     * 주차요금여부 (TB_PBLPKLT.prk_crg_yn, {@code char(1)}).
     *
     * <p>{@code Y}=유료 · {@code N}=무료 · 원천 결측이면 null. 컬럼이 {@code char(1)} 이라
     * 공백 패딩 없이 한 글자로 온다(2026-09-21 {@code octet_length} 실측 1).
     */
    @Schema(description = "주차요금여부 (Y=유료, N=무료, 원천 결측이면 null)", example = "Y",
            allowableValues = {"Y", "N"}, nullable = true)
    private String prkCrgYn;

    /** 주차장구분코드 (TB_PBLPKLT.pklt_type_cd). 공통코드 PKLT_TYPE_CD 의 cd_vl */
    @Schema(description = "주차장구분코드", example = "ONSTR", nullable = true)
    private String pkltTypeCd;

    /**
     * 주차장구분명 — 공통코드 {@code PKLT_TYPE_CD} 의 {@code cd_nm}.
     *
     * <p>🔴 DB 컬럼 {@code TB_PBLPKLT.pklt_type_nm}(원천 원문)과 <b>이름이 같지만 다른 값</b>이다.
     * 원문은 {@code 노상(23년 조사)}·{@code 노외(공영)} 처럼 조사 표기가 섞여 화면에 쓰지 않는다.
     * <p>{@code pklt_type_cd} 가 공통코드에 없으면 {@code null} — 화면은 그 행을 생략한다.
     */
    @Schema(description = "주차장구분명 (공통코드 PKLT_TYPE_CD)", example = "노상주차장", nullable = true)
    private String pkltTypeNm;
}
