package jeju.datahub.analysis.service.impl;

import java.time.LocalDateTime;

import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.ToString;

/**
 * 분석변수 변경 이력 엔티티. (parking.TB_ANLS_VRBL_HSTRY — append 전용)
 *
 * <p>이력 1행 = 분석유형 1건의 저장 1회다. 값이 실제로 바뀐 저장만 행을 남긴다 —
 * 같은 값 재저장은 이력을 쌓지 않는다({@link AnalysisWeightServiceImpl} 5) 조기 반환).
 *
 * <p><b>조회는 이 엔티티로 하지 않는다.</b> 이력 목록은 페이징 조회라 MyBatis
 * ({@link AnalysisWeightMapper#selectHistories(int, String)})가 담당하고 결과는 조회 전용
 * {@link jeju.datahub.analysis.service.AnalysisWeightHstryVO} 로 받는다.
 *
 * <p>컬럼명은 DDL {@code database/migrations/sql/67-TB_ANLS_VRBL_STNG.sql} 기준으로 명시한다.
 * JPA 는 MyBatis 의 {@code map-underscore-to-camel-case} 설정과 <b>무관</b>하다.
 *
 * <p>🔴 {@code chg_dt} 는 DDL 에 {@code DEFAULT CURRENT_TIMESTAMP} 가 있지만 <b>서비스가 값을 채운다</b>.
 * JPA 는 {@code @DynamicInsert} 가 없으면 매핑된 컬럼을 항상 INSERT 문에 실어 DB DEFAULT 가
 * 무시되므로, 비워 두면 NULL 이 나가 NOT NULL 위반 500 이 난다.
 */
@Entity
@Table(name = "tb_anls_vrbl_hstry", schema = "parking")
@Getter
@Setter
@ToString
@NoArgsConstructor
public class AnlsVrblHstry {

    /**
     * 변경이력일련번호 (chg_hstry_sn, BIGINT PK).
     *
     * <p>값을 넣지 않는다 — DB identity({@code GENERATED BY DEFAULT AS IDENTITY})가 매기고
     * {@code save()} 직후 엔티티에 채워진다.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "chg_hstry_sn")
    private Long chgHstrySn;

    /**
     * 분석유형코드 (anls_type_cd, NOT NULL).
     *
     * <p>🔴 DDL 이 NOT NULL 이고 DEFAULT 가 없다 — 빼면 첫 저장에서 not-null 위반 500 이 난다.
     */
    @Column(name = "anls_type_cd", nullable = false, length = 30)
    private String anlsTypeCd;

    /** 변경항목명 (chg_artcl_nm, NOT NULL — 기록 시점의 분석유형명) */
    @Column(name = "chg_artcl_nm", nullable = false, length = 100)
    private String chgArtclNm;

    /**
     * 변경내용 (chg_cn, NOT NULL — 기록 시점에 조립해 굳힌 표시용 문장).
     *
     * <p>예: {@code 민원빈도 60 → 55, 단속건수 40 → 45}. 뒤에 지표명이 바뀌어도 과거 이력의 뜻이
     * 변하지 않도록 문장으로 굳힌다.
     */
    @Column(name = "chg_cn", nullable = false, length = 1000)
    private String chgCn;

    /** 변경사유 (chg_rsn, nullable — 사용자가 입력한 사유. 선택) */
    @Column(name = "chg_rsn", length = 300)
    private String chgRsn;

    /**
     * 이전변수JSON (bfr_vrbl_json, JSONB NOT NULL — 변경 전 스냅샷).
     *
     * <p>Hibernate 6 의 JSON 매핑. {@code @JdbcTypeCode(SqlTypes.JSON)} + {@link String} 조합이면
     * 포맷 매퍼가 문자열을 <b>그대로</b> 싣는다(재직렬화하지 않는다) — 서비스가 조립한 JSON 배열
     * {@code [{"vrblCd":…,"vrblNm":…,"stngVl":…}, …]} 이 그대로 jsonb 컬럼에 들어간다.
     */
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(name = "bfr_vrbl_json", nullable = false)
    private String bfrVrblJson;

    /** 이후변수JSON (aftr_vrbl_json, JSONB NOT NULL — 변경 후 스냅샷. 되돌리기·감사용) */
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(name = "aftr_vrbl_json", nullable = false)
    private String aftrVrblJson;

    /** 변경자아이디 (chnrg_id, NOT NULL — 저장한 로그인 사용자의 user_id. 2026-10-30 이전 행은 'system') */
    @Column(name = "chnrg_id", nullable = false, length = 20)
    private String chnrgId;

    /** 변경자명 (chnrg_nm, NOT NULL — 화면 표시용. 저장한 로그인 사용자의 user_nm. 2026-10-30 이전 행은 '시스템') */
    @Column(name = "chnrg_nm", nullable = false, length = 100)
    private String chnrgNm;

    /** 변경일시 (chg_dt, NOT NULL — 저장이 커밋된 시각. 서비스가 채운다. 위 클래스 주석 참고) */
    @Column(name = "chg_dt", nullable = false)
    private LocalDateTime chgDt;

    /**
     * 이력 1행 생성용 생성자. 이 엔티티로 만들어지는 행은 예외 없이 신규 INSERT(append)다.
     *
     * @param anlsTypeCd   분석유형코드 (NOT NULL — 경로변수 값)
     * @param chgArtclNm   변경항목명 (기록 시점의 분석유형명)
     * @param chgCn        변경내용 문장
     * @param chgRsn       변경사유 (선택, null 허용)
     * @param bfrVrblJson  변경 전 스냅샷 JSON
     * @param aftrVrblJson 변경 후 스냅샷 JSON
     * @param chnrgId      변경자 ID (로그인 사용자 user_id)
     * @param chnrgNm      변경자명 (로그인 사용자 user_nm)
     * @param chgDt        변경일시 (DB DEFAULT 가 무시되므로 반드시 채운다)
     */
    public AnlsVrblHstry(String anlsTypeCd, String chgArtclNm, String chgCn, String chgRsn,
            String bfrVrblJson, String aftrVrblJson, String chnrgId, String chnrgNm, LocalDateTime chgDt) {
        this.anlsTypeCd = anlsTypeCd;
        this.chgArtclNm = chgArtclNm;
        this.chgCn = chgCn;
        this.chgRsn = chgRsn;
        this.bfrVrblJson = bfrVrblJson;
        this.aftrVrblJson = aftrVrblJson;
        this.chnrgId = chnrgId;
        this.chnrgNm = chnrgNm;
        this.chgDt = chgDt;
    }
}
