package jeju.datahub.analysis.service.impl;

import java.time.LocalDateTime;

import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.ToString;

/**
 * 분석실행 엔티티. (parking.TB_ANLS_EXCN — 쓰기 전용)
 *
 * <p>분석 실행 이력 적재는 영속성 규칙상 JPA 담당이라 이 엔티티를 쓴다
 * ({@code .claude/rules/rule_persistence-jpa-mybatis.md} — 쓰기=JPA).
 * 집중 구역 분석 보고서 생성(TSK-4078)이 실행 1회 = 이 테이블 1행을 남긴다.
 *
 * <p><b>조회는 이 엔티티로 하지 않는다.</b> 대시보드 `최근 분석 실행`·보고서 스냅샷 조회는
 * {@code TB_COM_CD}·{@code TB_ADMDST}·{@code TB_RPTP} 를 엮는 JOIN 이라 MyBatis 담당이고
 * 결과는 조회 전용 VO 로 받는다 — 같은 테이블을 엔티티와 VO 로 겸용하지 않는다는 규칙에 따른다.
 *
 * <p>컬럼명은 DDL {@code database/migrations/sql/08-TB_ANLS_EXCN.sql} +
 * {@code 35-report-schema.sql}(sgg_nm 보강) + TSK-4078 Step 1(PK identity 전환) 기준으로 명시한다.
 * JPA 는 MyBatis 의 {@code map-underscore-to-camel-case} 설정과 <b>무관</b>하므로
 * {@code @Column(name=...)} 을 생략하면 안 된다 — 필드마다 반드시 하나씩 붙인다.
 *
 * <p>⚠️ <b>DB NOT NULL 은 4개</b>({@code anls_type_cd} · {@code excutr_id} · {@code excn_stts_cd} ·
 * {@code excn_dt})다. 지역 3형태(전체/시군구/읍면동)를 표현하려고 {@code sgg_nm}·{@code emd_cd} 는
 * nullable 로 둔다.
 */
@Entity
@Table(name = "tb_anls_excn", schema = "parking")
@Getter
@Setter
@ToString
@NoArgsConstructor
public class AnlsExcn {

    /**
     * 실행아이디 (excn_id, BIGINT PK).
     *
     * <p>값을 넣지 않는다 — DB identity({@code GENERATED BY DEFAULT AS IDENTITY})가 매기고
     * {@code save()} 직후 엔티티에 채워진다 (TSK-4078 Step 1). 시퀀스 조회 SQL 은 만들지 않는다.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "excn_id")
    private Long excnId;

    /** 분석유형코드 (anls_type_cd, <b>NOT NULL</b> — ANLS_TYPE_CD 공통코드). 이 작업은 'HOTSPOT' */
    @Column(name = "anls_type_cd", nullable = false, length = 30)
    private String anlsTypeCd;

    /** 실행자ID (excutr_id, <b>NOT NULL</b>) — 인증 도입 전 상수 'system' (D13) */
    @Column(name = "excutr_id", nullable = false, length = 20)
    private String excutrId;

    /**
     * 시군구명 (sgg_nm, nullable). NULL 이면 전체 지역.
     *
     * <p>🔴 {@code emdCd} 가 있으면 반드시 {@code TB_ADMDST} 값으로 채운다 — 비워 두면
     * 스냅샷 조회의 {@code sgg_nm || ' ' || emd_nm} 이 NULL 연결이 되어 지역명 전체가 사라진다.
     */
    @Column(name = "sgg_nm", length = 40)
    private String sggNm;

    /** 읍면동코드 (emd_cd, nullable, FK→TB_ADMDST). NULL 이면 시군구 전체 */
    @Column(name = "emd_cd", length = 8)
    private String emdCd;

    /** 분석시작일자 (anls_bgng_ymd, CHAR(8) — yyyyMMdd) */
    @Column(name = "anls_bgng_ymd", length = 8)
    private String anlsBgngYmd;

    /** 분석종료일자 (anls_end_ymd, CHAR(8) — yyyyMMdd) */
    @Column(name = "anls_end_ymd", length = 8)
    private String anlsEndYmd;

    /**
     * 분석설정값 (anls_param_json, <b>JSONB</b> nullable) — 재현 메타 (D8).
     *
     * <p>Hibernate 6 의 JSON 매핑. {@code @JdbcTypeCode(SqlTypes.JSON)} + {@link String} 조합이면
     * 포맷 매퍼가 문자열을 <b>그대로</b> 싣는다(재직렬화하지 않는다).
     *
     * <p>⚠️ 이 애노테이션을 빼면 {@code column "anls_param_json" is of type jsonb but expression is
     * of type character varying} 로 INSERT 가 깨진다.
     */
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(name = "anls_param_json")
    private String anlsParamJson;

    /** 실행상태코드 (excn_stts_cd, <b>NOT NULL</b> — EXCN_STTS_CD 공통코드). 동기 실행이라 항상 'DONE' */
    @Column(name = "excn_stts_cd", nullable = false, length = 30)
    private String excnSttsCd;

    /**
     * 실행일시 (excn_dt, <b>NOT NULL</b>) — 저장 시각.
     *
     * <p>서버 실시각({@code LocalDateTime.now()})을 쓴다.
     */
    @Column(name = "excn_dt", nullable = false)
    private LocalDateTime excnDt;
}
