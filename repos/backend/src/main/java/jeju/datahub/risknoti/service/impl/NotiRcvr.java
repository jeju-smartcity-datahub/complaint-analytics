package jeju.datahub.risknoti.service.impl;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.ToString;

/**
 * 알림 수신자 엔티티. (parking.TB_NOTI_RCVR — 쓰기 전용)
 *
 * <p>등록·활성화 토글·소프트 삭제는 영속성 규칙상 JPA 담당이라 이 엔티티를 쓴다
 * (쓰기=JPA).
 *
 * <p><b>조회는 이 엔티티로 하지 않는다.</b> 목록·단건은 공통코드 + {@code TB_ADMDST} +
 * 단계 매핑({@code TB_NOTI_RCVR_LVL})을 엮는 다중 LEFT JOIN + 컬렉션 접기라
 * MyBatis({@link RiskNotiMapper})가 담당하고 결과는 조회 전용
 * {@link jeju.datahub.risknoti.service.NotiReceiverVO} 로 받는다 —
 * 같은 테이블을 엔티티와 VO 로 겸용하지 않는다는 규칙에 따른다.
 *
 * <p>컬럼명은 DDL {@code database/migrations/sql/18-TB_NOTI_RCVR.sql} +
 * {@code 41-alert-columns.sql}(컬럼 보강·PK identity 전환) 기준으로 명시한다.
 * JPA 는 MyBatis 의 {@code map-underscore-to-camel-case} 설정과 무관하므로
 * {@code @Column(name=...)} 을 생략하면 안 된다.
 *
 * <p>🔴 <b>{@code use_yn}·{@code del_yn} 은 필드 초기값으로 채운다</b>(규칙 4-1).
 * 둘 다 {@code NOT NULL DEFAULT} 인데, JPA 는 {@code @DynamicInsert} 가 없으면 매핑된 컬럼을
 * <b>항상</b> INSERT 문에 실어 DB DEFAULT 가 무시된다 — 초기값이 없으면 NULL 이 나가 NOT NULL 위반 500 이다.
 * {@code del_yn} 을 매핑하는 이유는 소프트 삭제를 UPDATE 로 해야 하기 때문이고,
 * 매핑하는 순간 INSERT 에도 실리므로 초기값이 세트로 따라온다.
 *
 * <p>⚠️ <b>{@code risk_lvl_cd} 는 매핑하지 않는다.</b> 단계 그룹이 다중이 되면서
 * {@link NotiRcvrLvl} 로 이관된 deprecated 컬럼이고, 41- 마이그레이션이 {@code DROP NOT NULL}
 * 했으므로 INSERT 에서 빠져도 문제가 없다. {@code cntct_no} 도 화면·요청 바디에 대응 값이 없어(nullable)
 * 매핑하지 않는다.
 *
 * <p>⚠️ <b>{@code sgg_nm}·{@code emd_cd} 도 더 이상 매핑하지 않는다</b>. 지역이 다중이 되면서
 * {@link NotiRcvrRgn}({@code TB_NOTI_RCVR_RGN})로 이관된 DEPRECATED 컬럼이다 — 단계가
 * {@link NotiRcvrLvl} 로 간 선례와 같다. 컬럼은 DROP 하지 않았고 nullable 이라, 매핑에서 빠지면
 * 신규 행은 NULL 로 들어간다(아무도 다시 쓰지 않게 필드 자체를 없앴다).
 *
 * <p>🔴 <b>{@code user_id} 는 매핑한다</b>({@code NOT NULL}, 마이그레이션 89). 수신자는
 * {@code TB_USER} 에서 고르고 벨 매칭 키가 이 칸이다. 이름·이메일·부서는 등록 시점의 <b>복사본</b>이고
 * 조회 화면은 {@code TB_USER} 최신값을 JOIN 해 보인다.
 */
@Entity
@Table(name = "tb_noti_rcvr", schema = "parking")
@Getter
@Setter
@ToString
@NoArgsConstructor
public class NotiRcvr {

    /**
     * 수신자ID (rcvr_id, BIGINT PK).
     *
     * <p>값을 넣지 않는다 — DB identity({@code GENERATED BY DEFAULT AS IDENTITY})가 매기고
     * {@code save()} 직후 엔티티에 채워진다. 시퀀스 조회 SQL 은 만들지 않는다.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "rcvr_id")
    private Long rcvrId;

    /**
     * 사용자ID (user_id, <b>NOT NULL</b> — TB_USER.user_id, FK 없음). 등록 시 요청의 {@code userId} 를 넣는다.
     *
     * <p>🔴 활성({@code del_yn='N'}) 행은 사용자당 1개다 — 부분 유니크 인덱스 {@code uq_tb_noti_rcvr_user}.
     */
    @Column(name = "user_id", nullable = false, length = 20)
    private String userId;

    /** 소속부서 코드 (dept_cd — TB_DEPT). 등록 시 {@code TB_USER.dept_cd} 를 복사한다 — 무소속이면 NULL */
    @Column(name = "dept_cd", length = 30)
    private String deptCd;

    /** 수신자명 (rcvr_nm) — 등록 시 {@code TB_USER.user_nm} 복사본 */
    @Column(name = "rcvr_nm", length = 100)
    private String rcvrNm;

    /** 이메일 (eml) — 등록 시 {@code TB_USER.user_eml_addr} 복사본(🔴 VARCHAR 200 → 100 이라 서비스가 자른다) */
    @Column(name = "eml", length = 100)
    private String eml;

    /**
     * 통보채널 코드 (ntfctn_ch_cd).
     *
     * <p>POST 바디에 대응 필드가 없다(채널 선택 UI 가 없다 — 발송 자체가 범위 밖).
     * 시드 12행이 전부 {@code 'EMAIL'} 이라 신규 행도 서비스가 같은 값으로 채운다 (규칙 4-2).
     */
    @Column(name = "ntfctn_ch_cd", length = 30)
    private String ntfctnChCd;

    /**
     * 사용여부 (use_yn, <b>NOT NULL</b>) — 화면의 토글 스위치.
     *
     * <p>🔴 초기값 {@code "Y"} 필수 — 위 클래스 주석의 4-1) 참고. 등록은 항상 활성으로 만든다
     * (POST 바디에 대응 필드가 없다). 이후 {@code PATCH .../activation} 이 Y/N 을 바꾼다.
     */
    @Column(name = "use_yn", nullable = false, length = 1)
    private String useYn = "Y";

    /**
     * 삭제여부 (del_yn, <b>NOT NULL</b>) — 소프트 삭제 플래그.
     *
     * <p>🔴 초기값 {@code "N"} 필수 — 위 클래스 주석의 4-1) 참고.
     * DELETE 요청은 행을 지우지 않고 이 값을 {@code 'Y'} 로 바꾼다 — 발송기록
     * ({@code TB_NOTI_HSTRY_RCVR})이 {@code rcvr_id} 로 수신자를 참조하므로 하드 삭제는 FK 위반이고,
     * 지우면 과거 발송기록이 함께 날아간다.
     */
    @Column(name = "del_yn", nullable = false, length = 1)
    private String delYn = "N";
}
