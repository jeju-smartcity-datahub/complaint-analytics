package jeju.datahub.report.service.impl;

import java.time.LocalDateTime;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.ToString;

/**
 * 보고서 자동 생성 설정 엔티티. (parking.TB_RPTP_AUTO_CRT_STNG — 쓰기 전용)
 *
 * <p>등록·수정·삭제(소프트)는 영속성 규칙상 JPA 담당이라 이 엔티티를 쓴다
 * (쓰기=JPA).
 *
 * <p><b>조회는 이 엔티티로 하지 않는다.</b> 목록·단건은 공통코드 3종 + {@code TB_ADMDST} 를 엮는
 * 다중 LEFT JOIN 이라 MyBatis({@link ReportMapper})가 담당하고 결과는 조회 전용
 * {@link jeju.datahub.report.service.ReportSettingVO} 로 받는다 —
 * 같은 테이블을 엔티티와 VO 로 겸용하지 않는다는 규칙에 따른다.
 * (예외는 소프트 삭제·수정의 대상 행을 잡을 때뿐이고, 그때도 응답은 VO 로 되돌려준다.)
 *
 * <p>컬럼명은 DDL {@code database/migrations/sql/14-TB_RPTP_AUTO_CRT_STNG.sql} +
 * {@code 35-report-schema.sql}(컬럼 보강·PK identity 전환) 기준으로 명시한다.
 * JPA 는 MyBatis 의 {@code map-underscore-to-camel-case} 설정과 무관하므로
 * {@code @Column(name=...)} 을 생략하면 안 된다.
 *
 * <p>⚠️ <b>DB NOT NULL 은 4개</b>({@code crltn_cycl_cd} · {@code actvtn_yn} · {@code creatr_id} ·
 * {@code crt_dt})다. 등록 경로({@code ReportServiceImpl.createSetting})가 요청 바디와 무관하게
 * 반드시 채운다 — 요청 바디에는 이 4개에 대응하는 필드가 아예 없다.
 *
 * <p>🔁 2026-08-24 — {@code crltn_ymd}(배포일자)는 컬럼이 삭제됐다. 배포일자는 저장 대신
 * {@code ReportServiceImpl.calculateNextCrltnYmd} 가 조회 시점에 계산해 응답에 채운다.
 */
@Entity
@Table(name = "tb_rptp_auto_crt_stng", schema = "parking")
@Getter
@Setter
@ToString
@NoArgsConstructor
public class RptpAutoCrtStng {

    /**
     * 설정아이디 (stng_id, BIGINT PK).
     *
     * <p>값을 넣지 않는다 — DB identity({@code GENERATED BY DEFAULT AS IDENTITY})가 매기고
     * {@code save()} 직후 엔티티에 채워진다. 시퀀스 조회 SQL 은 만들지 않는다.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "stng_id")
    private Long stngId;

    /** 보고서종류 코드 (rptp_type_cd — ANLS_TYPE_CD 중 addl_atrb1 IN ('RPTP','BOTH') 3종만 허용) */
    @Column(name = "rptp_type_cd", length = 30)
    private String rptpTypeCd;

    /** 배포부서 코드 (crltn_dept_cd — TB_DEPT) */
    @Column(name = "crltn_dept_cd", length = 30)
    private String crltnDeptCd;

    /** 배포주기 코드 (crltn_cycl_cd, <b>NOT NULL</b> — CRLTN_CYCL_CD) */
    @Column(name = "crltn_cycl_cd", nullable = false, length = 30)
    private String crltnCyclCd;

    /** 배포기준월 (crltn_mm, SMALLINT 1~12). 주기가 MONTH 면 NULL 로 저장한다 */
    @Column(name = "crltn_mm")
    private Integer crltnMm;

    /** 배포기준일 (crltn_dd, SMALLINT 1~28 — 말일 편차를 피해 28 로 제한) */
    @Column(name = "crltn_dd")
    private Integer crltnDd;

    // 🔁 2026-08-24 — crltn_ymd(배포일자)·crltn_prd_rng(배포기간)·rptp_nm_rule(보고서명규칙)
    //    컬럼이 삭제됐다(45-DROP-RPTP-STNG-COLUMNS.sql). 앞의 둘은 시드 전용 표시 문구라
    //    그냥 사라졌고, 배포일자는 **저장을 그만두고 조회 시점 계산으로 바꿨다** —
    //    ReportServiceImpl.calculateNextCrltnYmd 가 그대로 살아 있어 API 응답
    //    (ReportSettingVO.crltnYmd)은 종전과 같이 내려간다. 오히려 저장값보다 정확하다:
    //    저장 방식은 다음 수정 전까지 지난 날짜를 그대로 들고 있었다.

    /**
     * 활성여부 (actvtn_yn, <b>NOT NULL</b>) — 배치가 이 설정을 돌릴지.
     *
     * <p>삭제 여부({@link #delDt})와는 뜻이 다르다. 등록은 항상 활성으로 만든다 —
     * 중지/재개 UI 가 아직 없어 요청 바디에 대응 필드가 없다.
     */
    @Column(name = "actvtn_yn", nullable = false)
    private Boolean actvtnYn;

    /** 생성자ID (creatr_id, <b>NOT NULL</b>) — 등록한 로그인 사용자의 user_id. 자동 생성 보고서의 생성자로도 쓰인다 */
    @Column(name = "creatr_id", nullable = false, length = 20)
    private String creatrId;

    /** 생성자명 (creatr_nm) — 화면 표시용. 등록 시 로그인 사용자명을 50자로 잘라 채운다. 구 행은 NULL 일 수 있다 */
    @Column(name = "creatr_nm", length = 50)
    private String creatrNm;

    /** 생성일시 (crt_dt, <b>NOT NULL</b>) — 등록 시점에만 채우고 수정에서는 건드리지 않는다 */
    @Column(name = "crt_dt", nullable = false)
    private LocalDateTime crtDt;

    /** 최근생성일시 (last_crt_dt) — 이 설정으로 보고서를 마지막으로 만든 시각. 배치의 몫이라 CRUD 는 건드리지 않는다 */
    @Column(name = "last_crt_dt")
    private LocalDateTime lastCrtDt;

    /** 시군구명 (sgg_nm). NULL 이면 전체 지역. emd_cd 가 오면 서버가 TB_ADMDST 에서 다시 채운다 */
    @Column(name = "sgg_nm", length = 40)
    private String sggNm;

    /** 읍면동코드 (emd_cd, FK→TB_ADMDST). NULL 이면 시군구 전체 */
    @Column(name = "emd_cd", length = 8)
    private String emdCd;

    /**
     * 삭제 시각 (del_dt). NULL=존재, 값 있음=삭제됨 (소프트 삭제).
     *
     * <p>DELETE 요청은 행을 지우지 않고 이 값을 채운다 — 하드 삭제는
     * {@code TB_RPTP} FK 위반을 내고 과거 보고서의 주기·부서·지역 표시를 함께 지운다.
     */
    @Column(name = "del_dt")
    private LocalDateTime delDt;
}
