package jeju.datahub.report.service.impl;

import java.time.LocalDateTime;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.ToString;

/**
 * 보고서 엔티티. (parking.TB_RPTP — 쓰기 전용)
 *
 * <p>보고서 등록은 영속성 규칙상 JPA 담당이라 이 엔티티를 쓴다
 * (쓰기=JPA).
 * `내보내기` 한 번이 {@code crt_type='MANUAL'} 로 이 테이블 1행을 남긴다.
 *
 * <p><b>조회는 이 엔티티로 하지 않는다.</b> 목록·단건은 {@code TB_ANLS_EXCN}·
 * {@code TB_RPTP_AUTO_CRT_STNG}·공통코드·{@code TB_ADMDST} 를 엮는 다중 LEFT JOIN 이라
 * MyBatis({@link ReportMapper})가 담당하고 결과는 조회 전용
 * {@link jeju.datahub.report.service.ReportListVO} 로 받는다 — 같은 테이블을 엔티티와 VO 로
 * 겸용하지 않는다는 규칙에 따른다.
 *
 * <p>컬럼명은 DDL {@code database/migrations/sql/15-TB_RPTP.sql} +
 * {@code 35-report-schema.sql}(컬럼 보강·PK identity 전환) 기준으로 명시한다.
 * JPA 는 MyBatis 의 {@code map-underscore-to-camel-case} 설정과 <b>무관</b>하므로
 * {@code @Column(name=...)} 을 생략하면 안 된다 — 필드마다 반드시 하나씩 붙인다.
 *
 * <p>⚠️ <b>DB NOT NULL 은 3개</b>({@code crt_type} · {@code rptp_nm} · {@code stts_cd})다.
 * 직접 생성 경로가 요청 바디와 무관하게 반드시 채운다.
 * ({@code file_fmt} 는 NOT NULL 이 풀렸다 — 마이그레이션 72.)
 *
 * <p>{@link #stngId}·{@link #trgtPrdCd}·{@link #crltnDeptCd}·{@link #crltnCyclCd} 는
 * <b>자동 생성 전용 칸</b>이라 직접 생성 경로에서는 NULL 로 남긴다 — 필드로는 두어 나중에
 * 자동 생성 배치가 같은 엔티티를 쓰게 한다. (유니크 제약 {@code uq_rptp_stng_prd(stng_id,
 * trgt_prd_cd)} 는 PostgreSQL 기본 규칙상 NULL 을 서로 다른 값으로 보므로 MANUAL 행이
 * 여러 건이어도 충돌하지 않는다.)
 */
@Entity
@Table(name = "tb_rptp", schema = "parking")
@Getter
@Setter
@ToString
@NoArgsConstructor
public class Rptp {

    /**
     * 보고서ID (rptp_id, BIGINT PK).
     *
     * <p>값을 넣지 않는다 — DB identity({@code GENERATED BY DEFAULT AS IDENTITY})가 매기고
     * {@code save()} 직후 엔티티에 채워진다.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "rptp_id")
    private Long rptpId;

    /**
     * 생성구분 (crt_type, <b>NOT NULL</b> — RPTP_CRT_TYPE).
     *
     * <p>직접 생성은 {@code 'MANUAL'} — 이 값이 보고서 목록의 `직접 생성 보고서` 탭에 뜨게 한다.
     */
    @Column(name = "crt_type", nullable = false, length = 20)
    private String crtType;

    /** 설정아이디 (stng_id, nullable, FK→TB_RPTP_AUTO_CRT_STNG) — 자동 생성 전용. 직접 생성은 NULL */
    @Column(name = "stng_id")
    private Long stngId;

    /** 실행아이디 (excn_id, nullable, FK→TB_ANLS_EXCN) — 직접 생성이 참조하는 분석 실행 ID */
    @Column(name = "excn_id")
    private Long excnId;

    /** 보고서명 (rptp_nm, VARCHAR(256) <b>NOT NULL</b>) — 이름 규칙은 HotspotReportNaming 이 조립한다 */
    @Column(name = "rptp_nm", nullable = false, length = 256)
    private String rptpNm;

    /** 분석기간 (anls_prd_expln, VARCHAR(100) nullable) — 표기 예 {@code 2025.12.01 ~ 2025.12.31} */
    @Column(name = "anls_prd_expln", length = 100)
    private String anlsPrdExpln;

    /** 상태코드 (stts_cd, <b>NOT NULL</b> — RPTP_STTS_CD). 동기 생성이라 항상 'DONE' */
    @Column(name = "stts_cd", nullable = false, length = 30)
    private String sttsCd;

    /**
     * 파일형식 (file_fmt, nullable — FILE_FMT). 직접 생성은 요청값 PDF | DOCX.
     *
     * <p>🔴 <b>자동 생성은 NULL</b> 이다 — 설정에 형식 칸이 없어 고를 창구가 없다.
     * 읽는 곳이 없는 기록용 칸이라(목록 화면에 컬럼이 없고 재다운로드는 그때 고른다) 의미 없는
     * {@code 'PDF'} 를 박아 넣는 대신 비워 둔다. DB 제약은 마이그레이션 72 가 풀었다.
     */
    @Column(name = "file_fmt", length = 20)
    private String fileFmt;

    /**
     * 파일경로 (file_path, nullable).
     *
     * <p>직접 생성은 NULL 로 둔다 — 문서는 서버에 저장하지 않고 프론트가 스냅샷으로 다시 그린다.
     */
    @Column(name = "file_path", length = 300)
    private String filePath;

    /** 생성자ID (creatr_id, nullable) — 인증 도입 전 상수 'system' */
    @Column(name = "creatr_id", length = 20)
    private String creatrId;

    /**
     * 생성일자 (crt_ymd, nullable) — 저장 시각.
     *
     * <p>서버 실시각({@code LocalDateTime.now()})을 쓴다 — 대시보드 `최근 리포트`(crt_ymd DESC)의
     * 정렬 기준이다.
     */
    @Column(name = "crt_ymd")
    private LocalDateTime crtYmd;

    /** 생성자명 (creatr_nm, nullable) — 화면 표시용. 인증 도입 전 상수 '관리자' */
    @Column(name = "creatr_nm", length = 50)
    private String creatrNm;

    /** 대상기간코드 (trgt_prd_cd, nullable) — 자동 생성 전용. 직접 생성은 NULL */
    @Column(name = "trgt_prd_cd", length = 20)
    private String trgtPrdCd;

    /** 배포부서 코드 (crltn_dept_cd, nullable — TB_DEPT) — 자동 생성 전용. 직접 생성은 NULL */
    @Column(name = "crltn_dept_cd", length = 30)
    private String crltnDeptCd;

    /** 배포주기 코드 (crltn_cycl_cd, nullable — CRLTN_CYCL_CD) — 자동 생성 전용. 직접 생성은 NULL */
    @Column(name = "crltn_cycl_cd", length = 30)
    private String crltnCyclCd;
}
